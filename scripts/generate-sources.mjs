import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const markdownRoot = 'Investigation (.md)';
const pdfRoot = 'investigation';
const starterRoot = 'references';
const reportPath = join(root, starterRoot, 'README.md');
const collator = new Intl.Collator('en', { numeric: true, sensitivity: 'base' });
const compare = (a, b) => collator.compare(a, b) || (a === b ? 0 : a < b ? -1 : 1);

async function listFiles(directory, matches) {
  const folders = [directory];
  const files = [];
  while (folders.length) {
    const folder = folders.pop();
    for (const entry of await readdir(join(root, folder), { withFileTypes: true })) {
      const path = folder + '/' + entry.name;
      if (entry.isDirectory()) folders.push(path);
      else if (entry.isFile() && matches(entry.name)) files.push(path);
    }
  }
  return files.sort(compare);
}

const read = path => readFile(join(root, path), 'utf8');
const isMarkdown = name => /\.md$/i.test(name) && !/^readme\.md$/i.test(name);
const [markdownPaths, pdfPaths, starterPaths, manifestText] = await Promise.all([
  listFiles(markdownRoot, isMarkdown),
  listFiles(pdfRoot, name => /\.pdf$/i.test(name)),
  listFiles(starterRoot, isMarkdown),
  read(markdownRoot + '/conversion_manifest.json')
]);
const manifest = JSON.parse(manifestText);
const pairedPaths = new Map(manifest.document_pairs.map(item => [item.markdown, item.pdf]));
const pdfMetadata = new Map(manifest.pdfs.map(item => [item.path, item]));
const pdfByPath = new Map(pdfPaths.map(path => [path.toLowerCase(), path]));
const pdfByHash = new Map();
const citedPDFs = new Set();

for (const path of pdfPaths) {
  const hash = pdfMetadata.get(path)?.sha256 ??
    createHash('sha256').update(await readFile(join(root, path))).digest('hex');
  const equivalents = pdfByHash.get(hash) || [];
  equivalents.push(path);
  pdfByHash.set(hash, equivalents);
}

function citationTitle(markdown, path) {
  return markdown.match(/^#\s+(.+?)\s*$/m)?.[1] || basename(path, '.md');
}

function sourceURLs(markdown) {
  const matches = markdown.matchAll(/^(?:Source:\s*<?|source_url:\s*["']?|[ \t]*\[View original PDF\]\()(https?:\/\/[^\s"'<>)]+)/gim);
  return [...new Set(Array.from(matches, match => match[1]))];
}

function markdownLabel(label) {
  return label.replace(/[\\[\]|]/g, match => '\\' + match).replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function projectLink(label, path) {
  const fromCatalog = relative(dirname(reportPath), join(root, path)).split(sep);
  const url = fromCatalog.map(part => encodeURIComponent(part).replace(/[!'()*]/g,
    character => '%' + character.charCodeAt(0).toString(16).toUpperCase())).join('/');
  return '[' + markdownLabel(label) + '](' + url + ')';
}

function recordedLinks(urls) {
  return urls.map((url, index) => {
    const kind = new URL(url).hostname === 'drive.google.com' ? 'Collection copy' : 'Source';
    return '[' + kind + (urls.length > 1 ? ' ' + (index + 1) : '') + '](' + url + ')';
  }).join(' · ') || '—';
}

async function readCitation(path) {
  const markdown = await read(path);
  const title = citationTitle(markdown, path);
  const relativePath = path.slice(markdownRoot.length + 1);
  const [topic, ...folders] = relativePath.split('/');
  const displayFolder = folders.slice(0, -1).join(' / ');
  const hash = markdown.match(/^(?:source_sha256:\s*|Original PDF:\s*knowledge\/originals\/)([a-f0-9]{64})/im)?.[1]?.toLowerCase();
  const sameName = pdfRoot + '/' + relativePath.replace(/\.md$/i, '.pdf');
  const historical = markdown.match(/^Source location:\s*([^,\r\n]+\.pdf)/im)?.[1];
  const pdfs = [...new Set([
    pairedPaths.get(path),
    pdfByPath.get(sameName.toLowerCase()),
    ...(pdfByHash.get(hash) || []),
    ...pdfPaths.filter(pdf => historical && basename(pdf) === historical)
  ].filter(pdf => pdf && pdfByPath.has(pdf.toLowerCase())))];
  pdfs.forEach(pdf => citedPDFs.add(pdf));
  const urls = sourceURLs(markdown);
  return { path, title, topic, displayFolder, pdfs, urls };
}

const citations = [];
for (const path of markdownPaths) citations.push(await readCitation(path));
const topics = [...new Set(citations.map(citation => citation.topic))].sort(compare);
const pdfOnly = pdfPaths.filter(path => !citedPDFs.has(path));
